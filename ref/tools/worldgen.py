"""PS1-style world generators (see ref/world/procedural-recipes.md).

Two generators, both producing integer-unit geometry made of quads with baked
per-vertex colour (no runtime lighting needed), split into cullable chunks:

  terrain  - fBm value-noise heightfield on a grid, height-band palette,
             slope lighting + concavity AO baked into vertex colours.
  dungeon  - rooms on a sector grid (1024 units, Tomb Raider-style), joined by an
             MST of corridors plus a few loops, extruded into floor/ceiling/wall
             quads lit by baked torch falloff into black.

CLI:
    python -m ref.tools.worldgen terrain --out terrain.obj [--png preview.png] [--seed N] [--size 32]
    python -m ref.tools.worldgen dungeon --out dungeon.obj [--png preview.png] [--seed N] [--size 24]

World space is Y-up (OBJ convention). Colours in the OBJ are 0..1 vertex colours
("v x y z r g b"), readable by Blender and MeshLab.

WHY THESE CHOICES (the PS1 reasoning behind each)
=================================================
* Integer coordinates on a grid    PS1 vertices are 16-bit integers; grids also
                                   make collision trivial (look up the cell).
* Quads of similar size            Big polygons warp (affine texturing) and
                                   sort badly (one depth per polygon).
* Lighting baked into vertex colour   Runtime per-pixel lighting does not exist;
                                   colour stored per vertex is free to draw.
* Colours snapped to 32 levels     The framebuffer only has 5 bits per channel.
* Chunks                           Whole chunks can be skipped before any of
                                   their vertices are transformed.
* Deterministic seeds              The same seed always gives the same world,
                                   so a level can be stored as a single number.
"""

from __future__ import annotations

import argparse
import math
import random
from dataclasses import dataclass, field
from typing import Optional

SECTOR = 1024        # dungeon cell size (world units)
WALL_HEIGHT = 1024   # dungeon wall height


@dataclass
class Model:
    """Generator output: a plain indexed mesh with per-vertex colour and chunk groups."""
    vertices: list[tuple[int, int, int]] = field(default_factory=list)
    colors: list[tuple[int, int, int]] = field(default_factory=list)   # 0..255 per vertex
    faces: list[tuple[int, ...]] = field(default_factory=list)          # CCW rings seen from the front
    chunks: dict[tuple[int, int], list[int]] = field(default_factory=dict)  # chunk -> face indices

    def add_quad(self, pts, cols, chunk=None) -> None:
        """Append a quad with its own four vertices (walls need unshared
        vertices so each face can carry its own baked lighting)."""
        base = len(self.vertices)
        self.vertices += pts
        self.colors += cols
        self.faces.append(tuple(range(base, base + len(pts))))
        if chunk is not None:
            self.chunks.setdefault(chunk, []).append(len(self.faces) - 1)

    def stats(self) -> dict:
        sizes = [len(v) for v in self.chunks.values()] or [0]
        return {
            "vertices": len(self.vertices),
            "faces": len(self.faces),
            "chunks": len(self.chunks),
            "max_faces_per_chunk": max(sizes),
        }

    def to_obj(self) -> str:
        out = ["# generated by ref/tools/worldgen.py (PS1-style, baked vertex colour)"]
        for (x, y, z), (r, g, b) in zip(self.vertices, self.colors):
            out.append(f"v {x} {y} {z} {r / 255:.4f} {g / 255:.4f} {b / 255:.4f}")
        for key in sorted(self.chunks):
            out.append(f"g chunk_{key[0]}_{key[1]}")
            for fi in self.chunks[key]:
                out.append("f " + " ".join(str(i + 1) for i in self.faces[fi]))
        return "\n".join(out) + "\n"

    def to_raster_meshes(self):
        from .raster import Face, Mesh
        mesh = Mesh([tuple(map(float, v)) for v in self.vertices])
        for f in self.faces:
            mesh.faces.append(Face(f, colors=tuple(self.colors[i] for i in f)))
        return [mesh]


def quantize_color(c: tuple[float, float, float]) -> tuple[int, int, int]:
    """Clamp to 0..255 and snap to the 32 levels a 15-bit framebuffer can show.

    ``& 0xF8`` clears the low 3 bits, leaving multiples of 8: exactly the values
    a 5-bit channel can represent once expanded to 8 bits.
    """
    return tuple(int(max(0, min(255, round(v)))) & 0xF8 for v in c)


# ---------------------------------------------------------------- noise
#
# "Value noise": put a pseudo-random number on every integer grid point, then
# blend smoothly between the four surrounding points. Layering several copies
# at doubling frequency and halving strength ("fBm", fractal Brownian motion)
# gives large hills with smaller bumps on top: natural-looking terrain.

def _hash(ix: int, iy: int, seed: int) -> float:
    """Repeatable pseudo-random value in 0..1 for a grid point (integer hash).

    Multiplying by large odd constants and xor-shifting scrambles the bits so
    neighbouring points get unrelated values. No random-number state is needed.
    """
    h = (ix * 374761393 + iy * 668265263 + seed * 2147483647) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h ^ (h >> 16)) & 0xFFFF) / 0xFFFF


def value_noise(x: float, y: float, seed: int) -> float:
    """Smoothly interpolated noise at a real-valued position."""
    ix, iy = math.floor(x), math.floor(y)
    fx_, fy_ = x - ix, y - iy
    # Smoothstep (3t^2 - 2t^3) instead of plain t: flattens the curve at grid
    # points so there are no visible creases where cells meet.
    sx, sy = fx_ * fx_ * (3 - 2 * fx_), fy_ * fy_ * (3 - 2 * fy_)
    a, b = _hash(ix, iy, seed), _hash(ix + 1, iy, seed)
    c, d = _hash(ix, iy + 1, seed), _hash(ix + 1, iy + 1, seed)
    return (a + (b - a) * sx) + ((c + (d - c) * sx) - (a + (b - a) * sx)) * sy


def fbm(x: float, y: float, seed: int, octaves: int = 4) -> float:
    """Sum of ``octaves`` noise layers, each twice the frequency and half the
    amplitude of the last, normalised back to 0..1."""
    total, amp, freq, norm = 0.0, 1.0, 1.0, 0.0
    for o in range(octaves):
        total += value_noise(x * freq, y * freq, seed + o * 101) * amp
        norm += amp
        amp *= 0.5
        freq *= 2.0
    return total / norm


# ---------------------------------------------------------------- terrain

BANDS = [  # (max normalised height, colour) - painted-palette look
    (0.30, (200, 184, 120)),   # sand
    (0.55, (88, 152, 64)),     # grass
    (0.75, (64, 112, 48)),     # dark grass
    (0.90, (128, 112, 96)),    # rock
    (1.01, (232, 232, 240)),   # snow
]


def generate_terrain(size: int = 32, cell: int = 256, max_height: int = 1600, seed: int = 1,
                     chunk_cells: int = 8, light_dir=(0.5, 0.8, 0.3)) -> Model:
    """Grid of (size x size) quads. Heights are integers; colours are baked."""
    n = size + 1                      # N cells need N+1 corner samples per side
    # 1. Height field: noise sampled once per grid corner, normalised to 0..1,
    #    then scaled to whole world units (integers, like PS1 vertex data).
    hn = [[fbm(x / 8.0, z / 8.0, seed) for x in range(n)] for z in range(n)]
    lo = min(min(r) for r in hn)
    hi = max(max(r) for r in hn)
    hn = [[(v - lo) / (hi - lo or 1) for v in row] for row in hn]
    heights = [[int(v * max_height) for v in row] for row in hn]

    # 2. Bake lighting into each vertex colour, offline, so the renderer only
    #    has to interpolate colours. This is what PS1 level tools did.
    L = light_dir
    ll = math.sqrt(sum(c * c for c in L))
    L = tuple(c / ll for c in L)
    color_at = {}
    for z in range(n):
        for x in range(n):
            hl = heights[z][max(0, x - 1)]
            hr = heights[z][min(n - 1, x + 1)]
            hd = heights[max(0, z - 1)][x]
            hu = heights[min(n - 1, z + 1)][x]
            # Surface normal from the slope to the neighbours (central
            # differences): steep in x gives a large x component, and so on.
            nx, ny, nz = (hl - hr), 2.0 * cell, (hd - hu)
            nl = math.sqrt(nx * nx + ny * ny + nz * nz)
            # Lambert lighting: brightness = cos(angle between normal and sun).
            diffuse = max(0.0, (nx * L[0] + ny * L[1] + nz * L[2]) / nl)
            # concavity AO: darker where neighbours are higher than this vertex
            concave = ((hl + hr + hd + hu) / 4 - heights[z][x]) / max(1, max_height)
            ao = max(0.55, min(1.0, 1.0 - concave * 4))
            # Base colour from a small hand-picked palette by height: reads as
            # "painted", the way PS1 art was, rather than photographic.
            band = next(c for h, c in BANDS if hn[z][x] <= h)
            k = (0.35 + 0.75 * diffuse) * ao
            color_at[(x, z)] = quantize_color(tuple(c * k for c in band))

    # 3. Geometry: one vertex per sample, one quad per cell, grouped into chunks.
    m = Model()
    for z in range(n):  # shared vertex grid: one vertex per height sample, like a PS1 terrain chunk
        for x in range(n):
            m.vertices.append((x * cell, heights[z][x], z * cell))
            m.colors.append(color_at[(x, z)])
    for z in range(size):
        for x in range(size):
            corners = [(x, z), (x, z + 1), (x + 1, z + 1), (x + 1, z)]  # CCW seen from above (+Y)
            m.faces.append(tuple(cz * n + cx for cx, cz in corners))
            m.chunks.setdefault((x // chunk_cells, z // chunk_cells), []).append(len(m.faces) - 1)
    return m


# ---------------------------------------------------------------- dungeon

@dataclass
class Room:
    """A rectangle of open cells on the dungeon grid."""
    x: int
    y: int
    w: int
    h: int

    @property
    def center(self) -> tuple[int, int]:
        return self.x + self.w // 2, self.y + self.h // 2

    def overlaps(self, o: "Room", pad: int = 1) -> bool:
        return not (self.x + self.w + pad <= o.x or o.x + o.w + pad <= self.x or
                    self.y + self.h + pad <= o.y or o.y + o.h + pad <= self.y)


def generate_dungeon_grid(size: int = 24, rooms: int = 8, seed: int = 1, extra_loops: int = 2):
    """Return (grid, rooms) where grid[y][x] is True for open cells."""
    rng = random.Random(seed)          # own RNG: same seed -> same dungeon
    # 1. Rooms: try random rectangles, keep the ones that do not overlap
    #    (with a 1-cell gap so walls separate them). Give up after enough tries.
    placed: list[Room] = []
    for _ in range(rooms * 30):
        if len(placed) >= rooms:
            break
        w, h = rng.randint(3, 6), rng.randint(3, 6)
        r = Room(rng.randint(1, size - w - 1), rng.randint(1, size - h - 1), w, h)
        if not any(r.overlaps(o) for o in placed):
            placed.append(r)
    grid = [[False] * size for _ in range(size)]
    for r in placed:
        for yy in range(r.y, r.y + r.h):
            for xx in range(r.x, r.x + r.w):
                grid[yy][xx] = True

    # 2. Connections. A minimum spanning tree links every room using the
    #    shortest total corridor length, so everything is reachable. Prim's
    #    algorithm: start from room 0, repeatedly add the closest outside room.
    #    A tree alone has dead ends everywhere; a few extra random edges add
    #    loops, which make levels nicer to explore.
    # Prim's MST over room centres (Manhattan distance), then a few extra edges for loops.
    def dist(a, b):
        (ax, ay), (bx, by) = a.center, b.center
        return abs(ax - bx) + abs(ay - by)

    edges = []
    if placed:
        in_tree = {0}
        while len(in_tree) < len(placed):
            best = min(((dist(placed[i], placed[j]), i, j) for i in in_tree for j in range(len(placed)) if j not in in_tree))
            edges.append((best[1], best[2]))
            in_tree.add(best[2])
        candidates = [(i, j) for i in range(len(placed)) for j in range(i + 1, len(placed)) if (i, j) not in edges and (j, i) not in edges]
        rng.shuffle(candidates)
        edges += candidates[:extra_loops]

    # 3. Carve each connection as an L-shaped corridor (horizontal then
    #    vertical, or the other way round, chosen at random).
    for i, j in edges:  # L-shaped corridors
        (x0, y0), (x1, y1) = placed[i].center, placed[j].center
        if rng.random() < 0.5:
            for xx in range(min(x0, x1), max(x0, x1) + 1):
                grid[y0][xx] = True
            for yy in range(min(y0, y1), max(y0, y1) + 1):
                grid[yy][x1] = True
        else:
            for yy in range(min(y0, y1), max(y0, y1) + 1):
                grid[yy][x0] = True
            for xx in range(min(x0, x1), max(x0, x1) + 1):
                grid[y1][xx] = True
    return grid, placed


def _subdivide(q, k: int):
    """Split a planar quad (ring order) into k x k quads by bilinear interpolation."""
    if k <= 1:
        return [q]
    p0, p1, p2, p3 = q

    def at(s_, t_):
        a = [p0[i] + (p3[i] - p0[i]) * s_ for i in range(3)]
        b = [p1[i] + (p2[i] - p1[i]) * s_ for i in range(3)]
        return tuple(int(round(a[i] + (b[i] - a[i]) * t_)) for i in range(3))

    out = []
    for i in range(k):
        for j in range(k):
            s0, s1, t0, t1 = i / k, (i + 1) / k, j / k, (j + 1) / k
            out.append([at(s0, t0), at(s0, t1), at(s1, t1), at(s1, t0)])
    return out


def generate_dungeon(size: int = 24, rooms: int = 8, seed: int = 1, chunk_cells: int = 4, subdiv: int = 2) -> Model:
    """``subdiv`` splits every sector face k x k: PS1 games subdivided geometry the camera
    gets close to, to limit affine warping, sorting errors and near-plane dropout."""
    grid, placed = generate_dungeon_grid(size, rooms, seed)
    # One torch in the middle of each room. Light falls off with distance and
    # fades to near-black, like the black "fog" PS1 dungeons used to hide how
    # little could be drawn.
    torches = [((r.center[0] + 0.5) * SECTOR, (r.center[1] + 0.5) * SECTOR) for r in placed]
    torch_color = (255, 176, 96)
    radius = 4.5 * SECTOR

    def light(px: float, py: float, pz: float, base: tuple[int, int, int]) -> tuple[int, int, int]:
        k = 0.08  # ambient - falls off to near-black like a black depth cue
        for tx, tz in torches:
            d = math.sqrt((px - tx) ** 2 + (pz - tz) ** 2 + (py - WALL_HEIGHT * 0.7) ** 2)
            k += max(0.0, 1.0 - d / radius) ** 2 * 1.4
        return quantize_color(tuple(b * k * t / 255 for b, t in zip(base, torch_color)))

    floor_c, ceil_c, wall_c = (150, 130, 110), (90, 84, 80), (170, 160, 150)
    m = Model()
    S, H = SECTOR, WALL_HEIGHT

    def add(q, base, ch):
        for sq in _subdivide(q, subdiv):
            m.add_quad(sq, [light(*p, base) for p in sq], ch)

    def open_(x, y):
        return 0 <= x < size and 0 <= y < size and grid[y][x]

    # Extrude the 2D grid into 3D: every open cell gets a floor and a ceiling,
    # and a wall on each side that touches a solid cell. Each quad's corner
    # order is chosen so its front faces INTO the open cell (back-face culling
    # then hides the outside of the walls automatically).
    for y in range(size):
        for x in range(size):
            if not grid[y][x]:
                continue
            ch = (x // chunk_cells, y // chunk_cells)
            x0, x1, z0, z1 = x * S, (x + 1) * S, y * S, (y + 1) * S
            floor = [(x0, 0, z0), (x0, 0, z1), (x1, 0, z1), (x1, 0, z0)]   # faces +Y
            ceil = [(x0, H, z0), (x1, H, z0), (x1, H, z1), (x0, H, z1)]    # faces -Y
            add(floor, floor_c, ch)
            add(ceil, ceil_c, ch)
            # walls face into the open cell
            if not open_(x, y - 1):
                q = [(x0, 0, z0), (x1, 0, z0), (x1, H, z0), (x0, H, z0)]   # faces +Z
                add(q, wall_c, ch)
            if not open_(x, y + 1):
                q = [(x1, 0, z1), (x0, 0, z1), (x0, H, z1), (x1, H, z1)]   # faces -Z
                add(q, wall_c, ch)
            if not open_(x - 1, y):
                q = [(x0, 0, z1), (x0, 0, z0), (x0, H, z0), (x0, H, z1)]   # faces +X
                add(q, wall_c, ch)
            if not open_(x + 1, y):
                q = [(x1, 0, z0), (x1, 0, z1), (x1, H, z1), (x1, H, z0)]   # faces -X
                add(q, wall_c, ch)
    m.rooms = placed  # type: ignore[attr-defined]
    m.grid = grid     # type: ignore[attr-defined]
    return m


def ascii_map(grid) -> str:
    return "\n".join("".join("." if c else "#" for c in row) for row in grid)


# ---------------------------------------------------------------- preview

def render_preview(model: Model, kind: str):
    """Render the model at 320x240 through ref/tools/raster.py with PS1 rules and
    fog matching the background colour. Returns (Framebuffer, stats)."""
    from .raster import Camera, Framebuffer, RenderSettings, render_mesh

    xs = [v[0] for v in model.vertices]
    zs = [v[2] for v in model.vertices]
    if kind == "terrain":
        fog = (176, 200, 224)
        cam = Camera(position=(min(xs) - 600, 2600, min(zs) - 600), yaw=math.radians(45), pitch=math.radians(22), h=200)
        settings = RenderSettings(fog=(fog, 3500, 10000), z_max=12000)
    else:
        fog = (0, 0, 0)
        r = model.rooms[0]  # type: ignore[attr-defined]
        cam = Camera(position=(r.x * SECTOR + 200, WALL_HEIGHT * 0.5, r.y * SECTOR + 200), yaw=math.radians(40), pitch=math.radians(4), h=160)
        settings = RenderSettings(fog=(fog, 1500, 7000), z_max=12000, near=48)
    fb = Framebuffer(320, 240, clear=fog)
    stats = render_mesh(fb, model.to_raster_meshes(), cam, settings)
    return fb, stats


def preview(model: Model, path: str, kind: str, scale: int = 2) -> dict:
    """Render the preview and save it as a PNG; returns render stats."""
    fb, stats = render_preview(model, kind)
    fb.save_png(path, scale=scale)
    return stats


def main(argv: Optional[list[str]] = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m ref.tools.worldgen", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("kind", choices=["terrain", "dungeon"])
    ap.add_argument("--out", required=True, help="OBJ output path")
    ap.add_argument("--png", help="also render a PS1-style 320x240 preview (pure Python, takes a few seconds)")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--size", type=int, default=None)
    a = ap.parse_args(argv)
    if a.kind == "terrain":
        model = generate_terrain(size=a.size or 32, seed=a.seed)
    else:
        model = generate_dungeon(size=a.size or 24, seed=a.seed)
        print(ascii_map(model.grid))  # type: ignore[attr-defined]
    with open(a.out, "w") as f:
        f.write(model.to_obj())
    print(f"wrote {a.out}: {model.stats()}")
    if a.png:
        st = preview(model, a.png, a.kind)
        print(f"wrote {a.png}: {st}")


if __name__ == "__main__":
    main()
